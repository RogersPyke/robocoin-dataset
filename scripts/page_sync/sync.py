#!/usr/bin/env python3
"""
This script is the CLI entry for page asset sync.
It only consumes existing `info.yaml` files generated by metadata stage.
It never triggers metadata collection.

A standard command:
python scripts/page_sync/sync.py \
  --db-cfg-path /mnt/db/postgresql_config.yaml \
  --target-dir /home/rogerspyke/projects \
  --log-level INFO \
  --update-videos \
  --crf 30
`--update-videos` is optional. When enabled, videos/thumbnails are regenerated.
`--crf` controls compression quality in range 0-51 (lower means better quality).
Core logic is implemented in `src/robocoin_dataset/page_sync/page_sync.py`.


# With HuggingFace upload
python scripts/page_sync/sync.py \
    --db-cfg-path db/postgresql_config.yaml \
    --target-dir /home/rogerspyke/projects \
    --hf-token your_hf_token \
    --hf-repo-id RogersPyke/robocoin_datamanager_assets \
    --crf 30 \
    --force-regenerate
"""

import argparse
import sys
from pathlib import Path


def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "Sync dataset information to page project - consume existing info.yaml and "
            "construct assets (YAML files and videos)"
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Basic usage with required arguments
  python scripts/page_sync/sync.py \\
    --db-cfg-path db/postgresql_config.yaml \\
    --target-dir /path/to/page-project

  # With debug logging
  python scripts/page_sync/sync.py \\
    --db-cfg-path db/postgresql_config.yaml \\
    --target-dir /path/to/page-project \\
    --log-level DEBUG

  # Force regenerate videos and thumbnails
  python scripts/page_sync/sync.py \\
    --db-cfg-path db/postgresql_config.yaml \\
    --target-dir /path/to/page-project \\
    --update-videos

  # With custom CRF value for video compression
  python scripts/page_sync/sync.py \\
    --db-cfg-path db/postgresql_config.yaml \\
    --target-dir /path/to/page-project \\
    --crf 23

  # With HuggingFace upload
  python scripts/page_sync/sync.py \\
    --db-cfg-path db/postgresql_config.yaml \\
    --target-dir /path/to/page-project \\
    --hf-token your_hf_token \\
    --hf-repo-id RogersPyke/robocoin_datamanager_assets

Output Structure:
  target-dir/  (THIS IS the assets root, no nested assets/ subdirectory)
    dataset_info/
      {dataset_name}.yml
      ...
    videos/
      {dataset_name}.mp4
        ...
        """,
    )

    parser.add_argument(
        "--db-cfg-path",
        type=str,
        required=True,
        help="Path to the PostgreSQL YAML config file (e.g., db/postgresql_config.yaml)",
    )

    parser.add_argument(
        "--target-dir",
        type=str,
        required=True,
        help="Assets root directory (will contain dataset_info/, videos/, info/, thumbnails/ directly)",
    )

    parser.add_argument(
        "--crf",
        type=int,
        default=18,
        help="CRF value for video compression (default: 18, range: 0-51, lower = better quality)",
    )

    parser.add_argument(
        "--update-videos",
        action="store_true",
        help="Force regenerate videos and thumbnails even if they exist (default: False)",
    )

    parser.add_argument(
        "--log-level",
        type=str,
        default="INFO",
        choices=["DEBUG", "INFO", "WARNING", "ERROR", "CRITICAL"],
        help="Logging level (default: INFO)",
    )

    parser.add_argument(
        "--force-regenerate",
        action="store_true",
        help="Regenerate page sync files even if the dataset already shows as COMPLETED",
    )

    parser.add_argument(
        "--hf-token",
        type=str,
        default=None,
        help="HuggingFace token for uploading assets (optional). If not provided, upload will be skipped.",
    )

    parser.add_argument(
        "--hf-repo-id",
        type=str,
        default=None,
        help="HuggingFace repository ID for uploading assets (optional). If not provided, upload will be skipped.",
    )

    args = parser.parse_args()

    db_cfg_path_str = args.db_cfg_path

    # Validate paths
    db_cfg_path = Path(db_cfg_path_str)
    if not db_cfg_path.exists():
        print(f"Error: DB config file not found: {db_cfg_path_str}", file=sys.stderr)
        sys.exit(1)

    target_dir = Path(args.target_dir)
    if not target_dir.exists():
        print(f"Error: Target directory not found: {args.target_dir}", file=sys.stderr)
        print("Please create the directory first or check the path.", file=sys.stderr)
        sys.exit(1)

    # Import and run the main function
    from robocoin_dataset.page_sync.page_sync import main as page_sync_main

    print("Starting page sync operation...")
    print(f"  Database config: {db_cfg_path}")
    print(f"  Target: {args.target_dir}")
    print(f"  CRF: {args.crf}")
    print(f"  Update videos: {args.update_videos}")
    print(f"  Log level: {args.log_level}")
    print()

    try:
        page_sync_main(
            db_path=str(db_cfg_path.absolute()),
            target_dir=str(target_dir.absolute()),
            crf=args.crf,
            update_videos=args.update_videos,
            log_level=args.log_level,
            force_regenerate=args.force_regenerate,
        )
        print("\nPage sync completed successfully.")

        # Optional HuggingFace upload
        if args.hf_token and args.hf_repo_id:
            print("\nStarting HuggingFace upload...")
            try:
                from robocoin_dataset.page_sync._upload import sync_assets_to_hf

                # target_dir IS the assets root (no nested assets/ subdirectory)
                assets_dir = target_dir
                commit_sha = sync_assets_to_hf(
                    assets_dir=str(assets_dir),
                    repo_id=args.hf_repo_id,
                    token=args.hf_token,
                )
                print(f"HuggingFace upload completed successfully. Commit SHA: {commit_sha}")
            except Exception as e:
                print(f"\nError during HuggingFace upload: {e}", file=sys.stderr)
                sys.exit(1)
        elif args.hf_token or args.hf_repo_id:
            print(
                "\nWARNING: Both --hf-token and --hf-repo-id must be provided for "
                "HuggingFace upload. Skipping upload."
            )
        else:
            print("\nHuggingFace upload skipped (no token/repo-id provided)")

    except KeyboardInterrupt:
        print("\nOperation cancelled by user", file=sys.stderr)
        sys.exit(130)
    except Exception as e:
        print(f"\nError during page sync: {e}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
